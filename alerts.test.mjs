import assert from 'node:assert/strict';
import {parseTpfText} from './scripts/tpf-parse.mjs';
import {matchingAlerts,feedState,isTPF} from './alerts-core.mjs';
const now=Date.parse('2026-11-27T17:00:00+01:00'),at=new Date(now).toISOString();
const fixture='Info trafic\nPerturbations en cours sur le réseau TPF\nService restreint lignes 1, 2, 6 et 11.\nTravaux et manifestations\nligne 9';
const data=parseTpfText(fixture,at);
assert.deepEqual(data.alerts[0].lines,['1','2','6','11']);
assert.equal(parseTpfText('Info trafic\nAucune perturbation sur le réseau TPF\nTravaux et manifestations',at).status,'clear');
assert.equal(parseTpfText('Navigation uniquement',at).status,'unknown');
assert.equal(parseTpfText('Info trafic\nPerturbations en cours sur le réseau TPF\nIncident non précisé\nTravaux et manifestations',at).alerts[0].lines.length,0);
const trip={operator:'TPF',line:'B 2',start:now+5*60000,end:now+15*60000};
assert.equal(matchingAlerts(data,trip,now).length,1);
assert.equal(matchingAlerts(data,{...trip,operator:'TL'},now).length,0);
assert.equal(matchingAlerts(data,{...trip,line:'12'},now).length,0);
assert.equal(matchingAlerts(data,{...trip,start:now+86400000,end:now+86500000},now).length,0);
assert.equal(matchingAlerts(data,trip,now+31*60000).length,0);
assert.equal(feedState(data,now+31*60000),'stale');
assert.equal(isTPF('Transports publics fribourgeois (TPF)'),true);
assert.equal(isTPF(''),false);
console.log('TPF alert tests OK');
