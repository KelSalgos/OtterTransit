import assert from 'node:assert/strict';
import {parseTpfText} from './scripts/tpf-parse.mjs';
import {matchingAlerts,feedState,isTPF} from './alerts-core.mjs';
const now=Date.parse('2026-11-27T17:00:00+01:00'),at=new Date(now).toISOString();
const fixture='Info trafic\nPerturbations en cours sur le réseau TPF\nService restreint lignes 1, 2, 6 et 11.\nTravaux et manifestations\nligne 9';
const data=parseTpfText(fixture,at);
assert.deepEqual(data.alerts[0].lines,['1','2','6','11']);
assert.equal(parseTpfText('Info trafic\nAucune perturbation sur le réseau TPF\nTravaux et manifestations',at).status,'clear');
assert.equal(parseTpfText('Navigation uniquement',at).status,'unknown');
assert.equal(parseTpfText('Info trafic\nPerturbations en cours sur le réseau TPF\nIncident non précisé\nTravaux et manifestations',at).alerts[0].lines.length,0);
const trip={operator:'TPF',line:'B 2',start:now+5*60000,end:now+15*60000};
assert.equal(matchingAlerts(data,trip,now).length,1);
assert.equal(matchingAlerts(data,{...trip,operator:'TL'},now).length,0);
assert.equal(matchingAlerts(data,{...trip,line:'12'},now).length,0);
assert.equal(matchingAlerts(data,{...trip,start:now+86400000,end:now+86500000},now).length,0);
assert.equal(matchingAlerts(data,trip,now+31*60000).length,0);
assert.equal(feedState(data,now+31*60000),'stale');
assert.equal(isTPF('Transports publics fribourgeois (TPF)'),true);
assert.equal(isTPF(''),false);
console.log('TPF alert tests OK');

const today='Info trafic\nPerturbations en cours sur le réseau TPF\n14h00 à 19h00 - lignes 1 2 3 5 6 7 8 9 11\nTravaux et manifestations';
const timed=parseTpfText(today,at);
assert.deepEqual(timed.alerts[0].lines,['1','2','3','5','6','7','8','9','11']);
assert.equal(timed.alerts[0].start,'2026-11-27T13:00:00.000Z');
assert.equal(timed.alerts[0].end,'2026-11-27T18:00:00.000Z');
assert.equal(matchingAlerts(timed,{...trip,start:Date.parse('2026-11-27T13:45:00+01:00'),end:Date.parse('2026-11-27T13:45:00+01:00')},now).length,0);
assert.equal(matchingAlerts(timed,{...trip,start:Date.parse('2026-11-27T19:15:00+01:00'),end:Date.parse('2026-11-27T19:15:00+01:00')},now).length,0);
assert.equal(matchingAlerts(timed,{...trip,start:Date.parse('2026-11-27T18:55:00+01:00'),end:Date.parse('2026-11-27T18:55:00+01:00')},now).length,1);
const separate=parseTpfText('Info trafic\nPerturbations en cours sur le réseau TPF\nLes lignes RE2 et RE3 sont concernées.\nLa restriction dure jusqu’à 19:00 environ.\nDernière mise à jour : 27.11.2026 16:58:32\nLes lignes S50 et S51 sont concernées.\nLa restriction dure jusqu’à 20:00 environ.\nDernière mise à jour : 27.11.2026 16:59:32\nTravaux et manifestations',at);
assert.deepEqual(separate.alerts.map(x=>x.lines),[['RE2','RE3'],['S50','S51']]);
assert.equal(separate.alerts[0].start,null);
assert.equal(separate.alerts[0].end,'2026-11-27T18:00:00.000Z');
assert.equal(separate.alerts[1].end,'2026-11-27T19:00:00.000Z');
assert.equal(separate.alerts[0].approximate,true);
assert.equal(matchingAlerts(separate,{operator:'TPF',line:'RE2',start:Date.parse('2026-11-27T19:30:00+01:00')},now).length,0);
console.log('TPF period tests OK');

const plannedFixture='Info trafic\nAucune perturbation sur le réseau TPF\nTravaux et manifestations\nInformations détaillées\nDu : 28.11.2026 - 04:00\nAu : 30.11.2026 - 02:00\nCause: travaux\nLa restriction dure du 28.11.2026, 04:00 au 30.11.2026, 02:00.\nLes lignes RE2 et RE3 sont concernées.\nDu : 26.11.2026 - 17:00\nAu : 04.12.2026 - 05:30\nCause: travaux\nLa restriction dure du 26.11.2026 au 04.12.2026, toujours de 17:00 à 05:30.\nLes lignes 9 sont concernées.\nDu : 05.12.2026 - 05:00\nAu : 05.12.2026 - 21:00\nCause: une manifestation\nLes lignes 2 et 6 sont concernées.';
const pd=parseTpfText(plannedFixture,at);
assert.equal(pd.status,'clear');assert.equal(pd.plannedStatus,'available');assert.equal(pd.planned.length,2);
const atTime=s=>Date.parse('2026-11-'+s+':00+01:00');
assert.equal(matchingAlerts(pd,{operator:'TPF',line:'RE2',start:atTime('28T04:30')},now).length,1);
assert.equal(matchingAlerts(pd,{operator:'TPF',line:'9',start:atTime('28T12:00')},now).length,0);
assert.equal(matchingAlerts(pd,{operator:'TPF',line:'9',start:atTime('28T18:00')},now).length,1);
assert.equal(matchingAlerts(pd,{operator:'TPF',line:'9',start:atTime('28T02:00')},now).length,1);
assert.equal(matchingAlerts(pd,{operator:'TL',line:'9',start:atTime('28T18:00')},now).length,0);
assert.equal(parseTpfText('Info trafic\nAucune perturbation sur le réseau TPF\nTravaux et manifestations',at).plannedStatus,'unknown');
console.log('TPF planned 48h tests OK');
